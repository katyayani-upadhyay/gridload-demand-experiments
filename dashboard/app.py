"""Streamlit dashboard over the committed report artifacts.

The page reads only files under reports/ so it can run on Streamlit Community
Cloud without the DuckDB warehouse or a pipeline run.
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd
import plotly.graph_objects as go
import streamlit as st

REPORTS = Path(__file__).resolve().parents[1] / "reports"
BLUE = "#4c72b0"
RED = "#b3261e"
GREY = "#8a8a8a"

st.set_page_config(page_title="gridload demand experiments", layout="wide")


@st.cache_data
def load_predictions() -> pd.DataFrame:
    frame = pd.read_parquet(REPORTS / "forecast_predictions.parquet")
    frame["local_timestamp"] = pd.to_datetime(frame["local_timestamp"])
    return frame


@st.cache_data
def load_csv(name: str) -> pd.DataFrame:
    return pd.read_csv(REPORTS / name)


@st.cache_data
def load_json(name: str) -> dict:
    return json.loads((REPORTS / name).read_text())


def forecast_tab() -> None:
    metrics = load_csv("forecast_metrics.csv").set_index("model")
    by_hour = load_csv("forecast_metrics_by_hour.csv")
    predictions = load_predictions()
    config = load_json("forecast_backtest_config.json")

    st.subheader("Day-ahead hourly load forecast, Spain")
    st.caption(
        f"Rolling-origin backtest {config['start']} to {config['end']}, refit every "
        f"{config['refit_every_days']} days, {config['n_hours_scored']:,} hours scored. "
        "Real data (OPSD)."
    )
    cols = st.columns(4)
    cols[0].metric("LightGBM WAPE", f"{metrics.loc['lightgbm', 'wape']:.2%}")
    cols[1].metric("Seasonal-naive WAPE", f"{metrics.loc['seasonal_naive', 'wape']:.2%}")
    cols[2].metric("LightGBM MAPE", f"{metrics.loc['lightgbm', 'mape']:.2%}")
    cols[3].metric("LightGBM bias", f"{metrics.loc['lightgbm', 'bias_pct']:+.2%}")

    dates = predictions["local_timestamp"].dt.date
    default_start = pd.Timestamp("2020-03-09").date()
    start, end = st.slider(
        "Window",
        min_value=dates.min(),
        max_value=dates.max(),
        value=(default_start, pd.Timestamp("2020-03-22").date()),
        format="YYYY-MM-DD",
    )
    window = predictions[(dates >= start) & (dates <= end)]

    fig = go.Figure()
    fig.add_trace(
        go.Scatter(
            x=window["local_timestamp"],
            y=window["actual"],
            name="Actual",
            line=dict(color="#222222", width=1.6),
        )
    )
    fig.add_trace(
        go.Scatter(
            x=window["local_timestamp"],
            y=window["lightgbm"],
            name="LightGBM",
            line=dict(color=BLUE, width=1.3),
        )
    )
    fig.add_trace(
        go.Scatter(
            x=window["local_timestamp"],
            y=window["seasonal_naive"],
            name="Seasonal naive",
            line=dict(color=GREY, width=1, dash="dot"),
        )
    )
    fig.update_layout(
        height=380,
        margin=dict(l=10, r=10, t=30, b=10),
        yaxis_title="MW",
        legend=dict(orientation="h"),
    )
    st.plotly_chart(fig, width="stretch")

    st.markdown("**Error by hour of day (WAPE)**")
    pivot = by_hour.pivot(index="local_hour", columns="model", values="wape")
    fig2 = go.Figure()
    fig2.add_trace(
        go.Bar(x=pivot.index, y=pivot["seasonal_naive"], name="Seasonal naive", marker_color=GREY)
    )
    fig2.add_trace(go.Bar(x=pivot.index, y=pivot["lightgbm"], name="LightGBM", marker_color=BLUE))
    fig2.update_layout(
        barmode="group",
        height=300,
        margin=dict(l=10, r=10, t=10, b=10),
        yaxis_tickformat=".1%",
        xaxis_title="Local hour",
    )
    st.plotly_chart(fig2, width="stretch")


def _effect_bar(fig: go.Figure, label: str, est: dict, color: str, relative: bool) -> None:
    scale = 1 / est["control_mean"] if relative else 1.0
    centre = est["difference"] * scale
    fig.add_trace(
        go.Scatter(
            x=[centre],
            y=[label],
            mode="markers",
            marker=dict(color=color, size=11),
            error_x=dict(
                type="data",
                symmetric=False,
                array=[(est["ci_high"] * scale) - centre],
                arrayminus=[centre - (est["ci_low"] * scale)],
                color=color,
                thickness=2,
                width=6,
            ),
            showlegend=False,
        )
    )


def experiment_tab() -> None:
    r = load_json("ab_results.json")
    st.subheader("Peak-time rebate A/B test")
    st.warning(
        "Simulated data. Households and the treatment effect are generated by a seeded "
        "simulator with a known 6 percent peak reduction; this view validates the analysis "
        "pipeline and is not an observed programme result."
    )
    cfg, power, srm = r["config"], r["power"], r["srm"]
    cuped, raw = r["primary_cuped"], r["primary_unadjusted"]
    cols = st.columns(5)
    cols[0].metric(
        "Peak kWh reduction (CUPED)",
        f"{-cuped['relative_lift']:.1%}",
        help="Treatment vs control, per household per day",
    )
    cols[1].metric(
        "95% CI",
        f"[{-cuped['ci_high'] / cuped['control_mean']:.1%}, "
        f"{-cuped['ci_low'] / cuped['control_mean']:.1%}]",
    )
    cols[2].metric("MDE at 80% power", f"{power['mde_relative']:.1%}")
    cols[3].metric("CUPED variance reduction", f"{r['cuped_variance_reduction']:.0%}")
    cols[4].metric(
        "SRM",
        "passed" if srm["passed"] else "FAILED",
        f"p = {srm['p_value']:.2f}",
        delta_color="off",
    )
    st.markdown(
        f"**Decision: {'SHIP' if r['ship'] else 'DO NOT SHIP'}** &nbsp; "
        f"({cfg['n_households']} households, peak window {cfg['peak_hours'][0]:02d}:00 "
        f"to {cfg['peak_hours'][-1] + 1:02d}:00)"
    )

    fig = go.Figure()
    _effect_bar(fig, "Peak kWh, difference in means", raw, GREY, relative=True)
    _effect_bar(fig, "Peak kWh, CUPED", cuped, BLUE, relative=True)
    for g in r["guardrails"]:
        if g["metric"] == "opt_out_rate":
            continue
        _effect_bar(
            fig,
            f"Guardrail: {g['metric'].replace('_', ' ')}",
            g,
            RED if not g["passed"] else "#3a7d44",
            relative=True,
        )
    fig.add_vline(x=0, line_color="#666666", line_width=1)
    fig.update_layout(
        height=320,
        margin=dict(l=10, r=10, t=10, b=10),
        xaxis_tickformat="+.1%",
        xaxis_title="Treatment effect relative to control mean (95% CI)",
    )
    st.plotly_chart(fig, width="stretch")

    rows = [
        {
            "metric": g["name"],
            "control": g["control_mean"],
            "treatment": g["treatment_mean"],
            "difference": g["difference"],
            "ci_low": g["ci_low"],
            "ci_high": g["ci_high"],
            "p_value": g["p_value"],
            "rule": g["rule"],
            "passed": g["passed"],
        }
        for g in r["guardrails"]
    ]
    st.dataframe(pd.DataFrame(rows), width="stretch", hide_index=True)
    st.markdown((REPORTS / "ab_decision.md").read_text().split("## Design", 1)[0].split("\n", 1)[1])


def causal_tab() -> None:
    r = load_json("did_results.json")
    monthly = load_csv("did_event_study.csv")
    weekly = load_csv("did_event_study_weekly.csv")
    did = r["did"]
    st.subheader("Lockdown difference-in-differences: Spain vs Portugal")
    st.caption("Real data. Treated: Spain (state of alarm 14 March 2020). Control: Portugal.")
    cols = st.columns(4)
    cols[0].metric("Differential effect on load", f"{did['effect_pct']:+.2%}")
    cols[1].metric("95% CI", f"[{did['effect_ci_low_pct']:+.1%}, {did['effect_ci_high_pct']:+.1%}]")
    cols[2].metric("Spain raw YoY, 14 Mar to 30 Apr", f"{r['year_over_year_change']['ES']:+.1%}")
    cols[3].metric("Portugal raw YoY, same window", f"{r['year_over_year_change']['PT']:+.1%}")

    st.markdown(
        "**Pre-trends: monthly Spain minus Portugal gap in log load, seasonally adjusted, "
        "relative to February 2020**"
    )
    x = pd.PeriodIndex(monthly["month"], freq="M").to_timestamp()
    fig = go.Figure()
    fig.add_trace(
        go.Scatter(
            x=pd.concat([pd.Series(x), pd.Series(x[::-1])]),
            y=pd.concat([monthly["ci_high"], monthly["ci_low"][::-1]]),
            fill="toself",
            fillcolor="rgba(76,114,176,0.18)",
            line=dict(width=0),
            showlegend=False,
            hoverinfo="skip",
        )
    )
    pre = ~monthly["is_post"]
    fig.add_trace(
        go.Scatter(
            x=x[pre], y=monthly.loc[pre, "coefficient"], name="pre-event", line=dict(color=BLUE)
        )
    )
    fig.add_trace(
        go.Scatter(
            x=x[~pre], y=monthly.loc[~pre, "coefficient"], name="post-event", line=dict(color=RED)
        )
    )
    fig.add_vline(x=pd.Timestamp("2020-03-14").timestamp() * 1000, line_dash="dash", line_color=RED)
    fig.add_hline(y=0, line_color="#666666", line_width=1)
    fig.update_layout(
        height=340,
        margin=dict(l=10, r=10, t=10, b=10),
        yaxis_title="log points",
        legend=dict(orientation="h"),
    )
    st.plotly_chart(fig, width="stretch")

    st.markdown(
        "**Weekly event study 2020: differential year-over-year log change, pre-event weeks "
        "normalised to zero**"
    )
    fig2 = go.Figure()
    for is_post, color, name in ((False, BLUE, "pre-event"), (True, RED, "post-event")):
        part = weekly[weekly["is_post"] == is_post]
        fig2.add_trace(
            go.Scatter(
                x=part["weeks_from_event"],
                y=part["coefficient"],
                mode="markers",
                name=name,
                marker=dict(color=color, size=9),
                error_y=dict(
                    type="data",
                    symmetric=False,
                    array=part["ci_high"] - part["coefficient"],
                    arrayminus=part["coefficient"] - part["ci_low"],
                    color=color,
                ),
            )
        )
    fig2.add_vline(x=-0.5, line_dash="dash", line_color=RED)
    fig2.add_hline(y=0, line_color="#666666", line_width=1)
    fig2.update_layout(
        height=340,
        margin=dict(l=10, r=10, t=10, b=10),
        xaxis_title="Weeks from the week of 14 March 2020",
        yaxis_title="log points",
        legend=dict(orientation="h"),
    )
    st.plotly_chart(fig2, width="stretch")

    st.markdown(
        f"Pre-trend slope {r['pre_trend_slope_per_year']:+.4f} log points per year "
        f"(p = {r['pre_trend_slope_p_value']:.2f}). Published estimates of the Spanish demand "
        "drop over "
        f"mid-March to April 2020 range from {abs(r['published_range_pct'][1]):.0%} to "
        f"{abs(r['published_range_pct'][0]):.1%}; the DiD is a relative estimate because "
        "Portugal locked down too."
    )
    with st.expander("Identifying assumption and limitations"):
        text = (REPORTS / "did_results.md").read_text()
        st.markdown(
            "## Identifying assumption"
            + text.split("## Identifying assumption", 1)[1].split("## Estimate", 1)[0]
        )
        st.markdown("## Limitations" + text.split("## Limitations", 1)[1])


st.title("gridload demand experiments")
st.caption(
    "Hourly electricity load for Spain and Portugal (Open Power System Data, 2015 to 2020): "
    "day-ahead forecasting, a simulated demand-response A/B test, and a lockdown "
    "difference-in-differences study."
)
tab1, tab2, tab3 = st.tabs(["Forecast", "A/B experiment (simulated)", "Lockdown DiD"])
with tab1:
    forecast_tab()
with tab2:
    experiment_tab()
with tab3:
    causal_tab()
